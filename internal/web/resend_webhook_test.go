const resendSecret = "whsec_dGVzdC1zZWNyZXQ=" // gitleaks:allow (test value)

type resendHTTP func(*http.Request) (*http.Response, error)

func (f resendHTTP) RoundTrip(r *http.Request) (*http.Response, error) { return f(r) }
func postResend(h http.Handler, body string, at time.Time, secret string) *httptest.ResponseRecorder {
	ts := strconv.FormatInt(at.Unix(), 10)
	key, _ := base64.StdEncoding.DecodeString(strings.TrimPrefix(secret, "whsec_"))
	mac := hmac.New(sha256.New, key)
	mac.Write([]byte("msg-test." + ts + "." + body))
	req := httptest.NewRequest("POST", "/webhooks/resend", strings.NewReader(body))
	req.Header.Set("svix-id", "msg-test")
	req.Header.Set("svix-timestamp", ts)
	req.Header.Set("svix-signature", "v1,invalid v1,"+base64.StdEncoding.EncodeToString(mac.Sum(nil)))
	rec := httptest.NewRecorder()
	h.ServeHTTP(rec, req)
	return rec
}

func TestResendSvixReferenceSignature(t *testing.T) {
	// Independent test vector published by Svix, not generated by our signer.
	const body = `{"event_type":"ping","data":{"success":true}}`
	r, _ := sending.NewResend("re_test")
	s := &web.Server{Resend: r, ResendWebhookSecret: "whsec_plJ3nmyCDGBKInavdOK15jsl", Now: func() time.Time { return time.Unix(1731705121, 0) }} // gitleaks:allow (Svix test vector)
	req := httptest.NewRequest("POST", "/webhooks/resend", strings.NewReader(body))
	req.Header.Set("svix-id", "msg_loFOjxBNrRLzqYUf")
	req.Header.Set("svix-timestamp", "1731705121")
	req.Header.Set("svix-signature", "v1,rAvfW3dJ/X/qxhsaXPOyyCGmRKsaKWcsNccKXlIktD0=")
	rec := httptest.NewRecorder()
	s.Routes().ServeHTTP(rec, req)
	if rec.Code != 200 {
		t.Fatalf("Svix reference signature rejected: %d %s", rec.Code, rec.Body)
	}
}

func TestResendWebhookRejectsInvalidRequestsBeforeFetching(t *testing.T) {
	s, _ := server(t)
	r, _ := sending.NewResend("re_test")
	r.HTTP = &http.Client{Transport: resendHTTP(func(*http.Request) (*http.Response, error) {
		t.Fatal("invalid webhook fetched content")
		return nil, nil
	})}
	s.Resend, s.ResendWebhookSecret = r, resendSecret
	body := `{"type":"email.received","data":{"email_id":"incoming-1"}}`
	for name, rec := range map[string]*httptest.ResponseRecorder{
		"bad key": postResend(s.Routes(), body, clock, "whsec_b3RoZXI="),
		"old":     postResend(s.Routes(), body, clock.Add(-10*time.Minute), resendSecret),
		"future":  postResend(s.Routes(), body, clock.Add(10*time.Minute), resendSecret),
	} {
		if rec.Code != 401 {
			t.Errorf("%s returned %d", name, rec.Code)
		}
	}
	unsigned := httptest.NewRecorder()
	s.Routes().ServeHTTP(unsigned, httptest.NewRequest("POST", "/webhooks/resend", strings.NewReader(body)))
	if unsigned.Code != 401 {
		t.Fatalf("unsigned request returned %d", unsigned.Code)
	}
	s.ResendWebhookSecret = ""
	if rec := postResend(s.Routes(), body, clock, resendSecret); rec.Code != 503 {
		t.Fatalf("missing secret returned %d", rec.Code)
	}
}

func TestResendInboundFetchesContentAndDeduplicates(t *testing.T) {
	s, _ := server(t)
	r, _ := sending.NewResend("re_test")
	calls := 0
	r.HTTP = &http.Client{Transport: resendHTTP(func(req *http.Request) (*http.Response, error) {
		calls++
		if req.Method != "GET" || req.URL.Path != "/emails/receiving/incoming-1" || req.Header.Get("Authorization") != "Bearer re_test" {
			t.Fatalf("unexpected fetch: %s %s", req.Method, req.URL)
		}
		return &http.Response{StatusCode: 200, Body: io.NopCloser(strings.NewReader(`{"id":"incoming-1","from":"Customer <customer@example.com>","to":["original@example.com"],"received_for":["in+acmeplumbing@in.visicomms.app"],"subject":"Please stop","text":"Unsubscribe","message_id":"<customer-1@example.com>","headers":{"Auto-Submitted":"no"},"attachments":[{"id":"file-1","filename":"note.txt","content_type":"text/plain","size":12}]}`))}, nil
	})}
	s.Resend, s.ResendWebhookSecret = r, resendSecret
	body := `{"type":"email.received","data":{"email_id":"incoming-1","to":["original@example.com"],"text":"forged webhook body"}}`
	for range 2 {
		if rec := postResend(s.Routes(), body, clock, resendSecret); rec.Code != 200 {
			t.Fatalf("receive: %d %s", rec.Code, rec.Body)
		}
	}
	var n int
	var text, attachment, source string
	var untrusted bool
	err := s.DB.QueryRow(context.Background(), `SELECT count(*), min(payload->>'text'), min(payload->'attachments'->0->>'key'), bool_and(untrusted) FROM events WHERE provider='resend' AND type='email.received'`).Scan(&n, &text, &attachment, &untrusted)
	if err != nil || n != 1 || !strings.Contains(text, "Unsubscribe") || !untrusted || attachment != "resend:incoming-1/file-1" {
		t.Fatalf("stored event: %d, %q, %q, untrusted=%v, %v", n, text, attachment, untrusted, err)
	}
	if err := s.DB.QueryRow(context.Background(), `SELECT source FROM opt_outs`).Scan(&source); err != nil || source != "inbound email" {
		t.Fatalf("opt-out missing: %q %v", source, err)
	}
	if calls != 2 {
		t.Fatalf("fetches=%d", calls)
	}
}

func TestResendInboundFetchFailureRequestsRetry(t *testing.T) {
	s, _ := server(t)
	r, _ := sending.NewResend("re_test")
	r.HTTP = &http.Client{Transport: resendHTTP(func(*http.Request) (*http.Response, error) {
		return &http.Response{StatusCode: 503, Body: io.NopCloser(strings.NewReader(`{}`))}, nil
	})}
	s.Resend, s.ResendWebhookSecret = r, resendSecret
	body := `{"type":"email.received","data":{"email_id":"incoming-1","to":["in+acmeplumbing@in.visicomms.app"]}}`
	if rec := postResend(s.Routes(), body, clock, resendSecret); rec.Code != 500 {
		t.Fatalf("fetch failure returned %d", rec.Code)
	}
	var n int
	if err := s.DB.QueryRow(context.Background(), `SELECT count(*) FROM events WHERE type='email.received'`).Scan(&n); err != nil || n != 0 {
		t.Fatalf("partial inbound event: %d,%v", n, err)
	}
}

func TestResendForwardingRoutesToGeneratedAddress(t *testing.T) {
	s, _ := server(t)
	r, _ := sending.NewResend("re_test")
	r.HTTP = &http.Client{Transport: resendHTTP(func(*http.Request) (*http.Response, error) {
		return &http.Response{StatusCode: 200, Body: io.NopCloser(strings.NewReader(`{"id":"incoming-1","from":"customer@example.com","to":["original@example.com"],"received_for":["original@example.com"],"text":"A new inquiry","message_id":"<forwarded@example.com>"}`))}, nil
	})}
	s.Resend, s.ResendWebhookSecret = r, resendSecret
	body := `{"type":"email.received","data":{"email_id":"incoming-1","to":["in+acmeplumbing@in.visicomms.app"]}}`
	if rec := postResend(s.Routes(), body, clock, resendSecret); rec.Code != 200 {
		t.Fatalf("forwarding: %d %s", rec.Code, rec.Body)
	}
	var n int
	if err := s.DB.QueryRow(context.Background(), `SELECT count(*) FROM events WHERE provider='resend' AND type='email.received'`).Scan(&n); err != nil || n != 1 {
		t.Fatalf("forwarded email not stored: %d,%v", n, err)
	}
}
